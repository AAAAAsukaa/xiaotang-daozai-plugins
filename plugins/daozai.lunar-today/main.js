function lunarDate(year, dateMs) {
    let [start, leapMonth, lengths] = CALENDAR[year - FIRST_DATA_YEAR];
    let offset = (dateMs - Date.UTC(year, 0, 1)) / DAY_MS - start;
    if (offset < 0) {
        year -= 1;
        [start, leapMonth, lengths] = CALENDAR[year - FIRST_DATA_YEAR];
        offset = (dateMs - Date.UTC(year, 0, 1)) / DAY_MS - start;
    }

    for (let index = 0; index < lengths.length; index++) {
        const days = lengths[index] === "1" ? 30 : 29;
        if (offset < days) {
            const isLeap = leapMonth > 0 && index === leapMonth;
            const month = leapMonth > 0 && index >= leapMonth ? index - 1 : index;
            return (isLeap ? "闰" : "") + MONTH_NAMES[month] + "月" + DAY_NAMES[offset];
        }
        offset -= days;
    }
}

function solarTerm(year, month, day) {
    const termDays = CALENDAR[year - FIRST_DATA_YEAR][3];
    const first = (month - 1) * 2;
    for (let index = first; index < first + 2; index++) {
        if (Number(termDays.slice(index * 2, index * 2 + 2)) === day) {
            return SOLAR_TERMS[index];
        }
    }
}

function displayDate(today) {
    if (typeof today !== "string" || !/^\d{4}-\d{2}-\d{2}$/.test(today)) {
        return "农历日期暂不可用";
    }
    const [year, month, day] = today.split("-").map(Number);
    if (year < FIRST_SUPPORTED_YEAR || year > LAST_SUPPORTED_YEAR) {
        return "农历日期暂不可用";
    }
    // 宿主已经提供本地日期，这里用 UTC 做日期运算，不套用系统时区。
    const dateMs = Date.UTC(year, month - 1, day);
    const date = new Date(dateMs);
    if (date.getUTCMonth() !== month - 1 || date.getUTCDate() !== day) {
        return "农历日期暂不可用";
    }
    const lunar = lunarDate(year, dateMs);
    if (!lunar) {
        return "农历日期暂不可用";
    }
    const term = solarTerm(year, month, day);
    return "农历" + lunar + (term ? " · " + term : "");
}

function refresh({ today }) {
    return { card: displayDate(today), storage: null };
}
